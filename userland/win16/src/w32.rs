//! W32USER's calls, which WIN16's USER and GDI are a facade over
//! (docs/WIN16.md, "One window manager"). Every argument is 32 bits;
//! handles are W32USER's small numbers, the same as WIN16's.

#![allow(dead_code)]

macro_rules! w32 {
    ($($name:ident($($a:ident),*);)*) => {
        unsafe extern "stdcall" {
            $(
                #[link_name = concat!("W32USER.", stringify!($name))]
                pub fn $name($($a: u32),*) -> u32;
            )*
        }
    };
}

