"""Generate userland/pmwp/src/classes_gen.rs: the Workplace Shell classes
PMWP.DLL provides, from the OS/2 Toolkit's IDL files (work/media/boot/
toolkit/os2tk45/idl): each class's parent, metaclass, version and its
methods in release order (the order of the tokens in <Class>ClassData,
which code compiled against the Toolkit relies on), and the ordinals of
<Class>ClassData, <Class>CClassData and <Class>NewClass in IBM's PMWP.DLL
(from userland/pmwp/ordinals.txt).

usage: python3 -I tools/scripts/gen_wps_classes.py REPO
"""
import glob, os, re, sys

repo = sys.argv[1]
idl_dir = os.path.join(repo, 'work/media/boot/toolkit/os2tk45/idl')
ords = {}
for line in open(os.path.join(repo, 'userland/pmwp/ordinals.txt')):
    line = line.split(';')[0].strip()
    if line:
        o, n = line.split()
        ords[n] = int(o)

classes = {}
for path in sorted(glob.glob(os.path.join(idl_dir, 'wp*.idl'))):
    src = open(path, errors='replace').read().replace('\r', '')
    src = re.sub(r'//[^\n]*', '', src)
    src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
    for m in re.finditer(r'\binterface\s+(\w+)\s*:\s*([\w, ]+?)\s*\{', src):
        name, parents = m.group(1), [p.strip() for p in m.group(2).split(',')]
        # The interface body: to the matching brace.
        i, depth = m.end(), 1
        while depth and i < len(src):
            depth += {'{': 1, '}': -1}.get(src[i], 0)
            i += 1
        body = src[m.end():i]
        impl = re.search(r'\bimplementation\s*\{(.*)\}', body, re.S)
        if not impl:
            continue
        impl = impl.group(1)
        ro = re.search(r'releaseorder\s*:(.*?);', impl, re.S)
        methods = [x.strip() for x in ro.group(1).split(',') if x.strip()] if ro else []
        meta = re.search(r'\bmetaclass\s*=\s*(\w+)', impl)
        major = re.search(r'majorversion\s*=\s*(\d+)', impl)
        minor = re.search(r'minorversion\s*=\s*(\d+)', impl)
        overrides = re.findall(r'\b(\w+)\s*:\s*override\b', impl)
        dll = re.search(r'dllname\s*=\s*"([^"]*)"', impl)
        classes[name] = dict(parents=parents, methods=methods, meta=meta.group(1) if meta else None,
                             major=int(major.group(1)) if major else 1, minor=int(minor.group(1)) if minor else 1,
                             overrides=overrides, dll=(dll.group(1).lower() if dll else ''), file=os.path.basename(path))

wanted = [n for n in classes if n + 'ClassData' in ords]
missing = sorted(set(k[:-9] for k in ords if k.endswith('ClassData') and not k.endswith('CClassData')) - set(wanted))
out = ['//! Generated by tools/scripts/gen_wps_classes.py from the OS/2 Toolkit\'s',
       '//! IDL files: the classes PMWP.DLL provides, their methods in release',
       '//! order (the order of the tokens in <Class>ClassData), and the ordinals',
       '//! of their class data and NewClass functions in IBM\'s PMWP.DLL.', '',
       'pub struct ClassDef {',
       '    pub name: &\'static str,',
       '    pub parents: &\'static [&\'static str],',
       '    pub meta: Option<&\'static str>,',
       '    pub major: u32,',
       '    pub minor: u32,',
       '    pub methods: &\'static [&\'static str],',
       '    /// Ordinals of <Class>ClassData, <Class>CClassData, <Class>NewClass.',
       '    pub ords: (u32, u32, u32),',
       '}', '',
       'pub static CLASSES: &[ClassDef] = &[']
# Parents before children.
done, order = set(), []
def add(n):
    if n in done or n not in wanted:
        return
    for p in classes[n]['parents']:
        add(p)
    if classes[n]['meta']:
        add(classes[n]['meta'])
    done.add(n)
    order.append(n)
for n in sorted(wanted):
    add(n)
for n in order:
    c = classes[n]
    o = (ords.get(n + 'ClassData', 0), ords.get(n + 'CClassData', 0), ords.get(n + 'NewClass', 0))
    out.append('    ClassDef {')
    out.append(f'        name: "{n}",')
    out.append('        parents: &[' + ', '.join(f'"{p}"' for p in c['parents']) + '],')
    out.append('        meta: ' + (f'Some("{c["meta"]}")' if c['meta'] else 'None') + ',')
    out.append(f'        major: {c["major"]},')
    out.append(f'        minor: {c["minor"]},')
    out.append('        methods: &[' + ', '.join(f'"{x}"' for x in c['methods']) + '],')
    out.append(f'        ords: ({o[0]}, {o[1]}, {o[2]}),')
    out.append('    },')
out.append('];')
# Method indexes (the token's position in <Class>ClassData, after the
# class object).
out.append('')
out.append('/// Method indexes in <Class>ClassData (after the class object).')
out.append('#[allow(non_snake_case, non_upper_case_globals, dead_code)]')
out.append('pub mod m {')
for n in order:
    out.append(f'    pub mod {n} {{')
    for i, x in enumerate(classes[n]['methods']):
        out.append(f'        pub const {x}: usize = {i};')
    out.append('    }')
out.append('}')
open(os.path.join(repo, 'userland/pmwp/src/classes_gen.rs'), 'w').write('\n'.join(out) + '\n')

# The class data (exported variables) and NewClass functions.
cd = ['//! Generated by tools/scripts/gen_wps_classes.py: the exported class data',
      '//! of the Workplace Shell classes and their NewClass functions.', '',
      '#![allow(non_upper_case_globals)]', '']
for n in order:
    k = len(classes[n]['methods'])
    cd.append('#[unsafe(no_mangle)]')
    cd.append(f'pub static mut {n}ClassData: [usize; {k + 1}] = [0; {k + 1}];')
    cd.append('#[unsafe(no_mangle)]')
    cd.append(f'pub static mut {n}CClassData: [usize; 8] = [0; 8];')
cd.append('')
for i, n in enumerate(order):
    cd.append('#[unsafe(no_mangle)]')
    cd.append(f'pub extern "C" fn {n}NewClass(major: i32, minor: i32) -> usize {{')
    cd.append(f'    crate::wps::new_class({i}, major, minor)')
    cd.append('}')
cd.append('')
cd.append('/// The class data of CLASSES[i]: ClassData, its length, CClassData.')
cd.append('pub fn class_data(i: usize) -> (*mut usize, usize, *mut usize) {')
cd.append('    unsafe {')
cd.append('        match i {')
for i, n in enumerate(order):
    cd.append(f'            {i} => ((&raw mut {n}ClassData) as *mut usize, {len(classes[n]["methods"]) + 1}, (&raw mut {n}CClassData) as *mut usize),')
cd.append('            _ => (core::ptr::null_mut(), 0, core::ptr::null_mut()),')
cd.append('        }')
cd.append('    }')
cd.append('}')
open(os.path.join(repo, 'userland/pmwp/src/classdata_gen.rs'), 'w').write('\n'.join(cd) + '\n')

# Ordinals: NewClass functions (exports.private) and the class data
# variables (exports.extra, after the lines that are not generated).
priv_path = os.path.join(repo, 'userland/pmwp/exports.private')
priv = [l.rstrip('\n') for l in open(priv_path)] if os.path.exists(priv_path) else []
priv = [l for l in priv if l.strip() and not l.split()[0].endswith('NewClass')]
priv += [f'{n}NewClass {ords[n + "NewClass"]}' for n in order if n + 'NewClass' in ords]
open(priv_path, 'w').write('\n'.join(priv) + '\n')
extra_path = os.path.join(repo, 'userland/pmwp/exports.extra')
keep = []
if os.path.exists(extra_path):
    for line in open(extra_path):
        if line.startswith('; Class data'):
            break
        keep.append(line.rstrip('\n'))
keep.append('; Class data (generated by tools/scripts/gen_wps_classes.py)')
for n in order:
    for suffix in ('ClassData', 'CClassData'):
        if n + suffix in ords:
            keep.append(f'{n}{suffix}={n}{suffix} @{ords[n + suffix]}')
open(extra_path, 'w').write('\n'.join(keep) + '\n')
print(len(order), 'classes;', 'not in the Toolkit:', ' '.join(missing))
