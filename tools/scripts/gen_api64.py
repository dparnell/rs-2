"""Generate the 64-bit API's C headers and Rust bindings (docs/API64.md).

One description, userland64/api/*.api, gives both languages the same
types, constants, structures and functions:

    userland64/include/NAME.h        (C: clang, freestanding)
    userland64/os2/src/api/NAME.rs   (Rust: the os2 crate, `os2::*`)

Each .api file is one header. Lines (`#` starts a comment):

    prim NAME "C type" rusttype      a basic type
    type NAME OTHER                  NAME is OTHER
    ptr NAME TARGET                  NAME is a pointer to TARGET
    cptr NAME TARGET                 ... to const TARGET
    const NAME VALUE [: TYPE]        a constant (TYPE: ULONG by default);
                                     VALUE is an expression both languages
                                     read (numbers, other constants, | + -)
    struct NAME [noptr]              a structure; field lines `TYPE name`
      TYPE field                     or `TYPE name[N]`, until `end`; PNAME
    end                              is declared too unless `noptr`
    fnptr NAME RET (TYPE, ...)       a pointer to a System V function
    fn MODULE.ORD RET Name(TYPE p, ...)   an import by ordinal
    fn MODULE RET Name(TYPE p, ...)       an import by name (MODULE.Name)
    include NAME                     the C header includes NAME.h
    c / rust ... end                 text for one language only, as is

The script checks what it can: DOSCALLS ordinals must be ones the kernel
lets 64-bit code call (kernel/src/api/api64.rs), and PMWIN functions must
be exports of the 32-bit PMWIN with the same number of arguments
(userland/pmwin/src/exports.rs), since the 64-bit PMWIN passes each
argument on as one 32-bit value.

usage: python3 -I tools/scripts/gen_api64.py
"""
import os, re, sys

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
api_dir = os.path.join(root, 'userland64/api')
inc_dir = os.path.join(root, 'userland64/include')
rs_dir = os.path.join(root, 'userland64/os2/src/api')

RUST_KEYWORDS = {'type', 'fn', 'mod', 'ref', 'match', 'move', 'loop', 'use', 'impl', 'in', 'self', 'box', 'where', 'struct', 'enum', 'priv', 'yield', 'async', 'await', 'dyn', 'const', 'static', 'trait', 'crate', 'super', 'pub', 'unsafe', 'let', 'mut', 'as', 'extern', 'final', 'override', 'macro', 'virtual', 'do', 'try', 'gen'}

# What 64-bit code may call: the ordinals api64.rs names.
api64 = open(os.path.join(root, 'kernel/src/api/api64.rs')).read()
dos_ok = set(int(n) for n in re.findall(r'\b(\d{2,4})\b', api64))
# The 32-bit PMWIN's exports: name -> argument count.
pm_args = {n: int(a) for n, a in re.findall(r'__a_(\w+) => [\w:]+, (\d+), \d+;', open(os.path.join(root, 'userland/pmwin/src/exports.rs')).read())}

errors = []
prims = {}      # name -> rust type


def rident(n):
    return f'r#{n}' if n in RUST_KEYWORDS else n


def rtype(t):
    t = t.strip()
    if t in ('VOID', 'void'):
        return 'c_void'
    return t


def parse_params(s):
    s = s.strip()
    if not s or s == 'VOID':
        return []
    out = []
    for i, p in enumerate(s.split(',')):
        parts = p.split()
        if len(parts) == 1:
            out.append((parts[0], f'a{i}'))
        else:
            out.append((' '.join(parts[:-1]), parts[-1]))
    return out


def gen(path):
    name = os.path.splitext(os.path.basename(path))[0]
    lines = open(path).read().split('\n')
    c, r = [], []
    guard = f'RS2_{name.upper()}_H'
    c += [f'/* {name}.h: rs2\'s 64-bit OS/2 API (docs/API64.md).', ' * Generated by tools/scripts/gen_api64.py from',
          f' * userland64/api/{name}.api. Do not edit. */', '', f'#ifndef {guard}', f'#define {guard}', '']
    r += [f'//! {name}: rs2\'s 64-bit OS/2 API (docs/API64.md). Generated by', f'//! tools/scripts/gen_api64.py from userland64/api/{name}.api. Do not edit.', '',
          '#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, dead_code, clippy::all)]', '', 'use super::*;', '']
    fns = []
    i = 0
    while i < len(lines):
        raw = lines[i]
        i += 1
        s = raw.split('#', 1)[0].strip()
        if not s:
            continue
        if s.startswith('#'):
            continue
        w = s.split(None, 1)
        kw = w[0]
        rest = w[1] if len(w) > 1 else ''
        if kw in ('c', 'rust') and rest == '':
            block = []
            while lines[i].strip() != 'end':
                block.append(lines[i])
                i += 1
            i += 1
            (c if kw == 'c' else r).extend(block + [''])
            continue
        if kw == 'include':
            c.append(f'#include "{rest}.h"')
        elif kw == 'prim':
            m = re.match(r'(\w+)\s+"([^"]+)"\s+(\S+)', rest)
            n, ct, rt = m.groups()
            prims[n] = rt
            c.append(f'typedef {ct} {n};')
            r.append(f'pub type {n} = {rt};')
        elif kw == 'type':
            n, o = rest.split()
            c.append(f'typedef {o} {n};')
            r.append(f'pub type {n} = {rtype(o)};')
        elif kw in ('ptr', 'cptr'):
            n, o = rest.split()
            c.append(f'typedef {"const " if kw == "cptr" else ""}{o} *{n};')
            r.append(f'pub type {n} = *{"const" if kw == "cptr" else "mut"} {rtype(o)};')
        elif kw == 'const':
            val, _, ty = rest.partition(' : ')
            n, val = val.split(None, 1)
            ty = ty.strip() or 'ULONG'
            c.append(f'#define {n} ({val})' if any(ch in val for ch in '-|+ ') else f'#define {n} {val}')
            r.append(f'pub const {n}: {rtype(ty)} = {val};')
        elif kw == 'struct':
            parts = rest.split()
            n = parts[0]
            noptr = 'noptr' in parts[1:]
            fields = []
            while lines[i].strip() != 'end':
                f = lines[i].split('#', 1)[0].strip()
                i += 1
                if not f:
                    continue
                m = re.match(r'(.+?)\s+(\w+)(?:\[(\w+)\])?$', f)
                fields.append(m.groups())
            i += 1
            c.append(f'typedef struct _{n} {{')
            for t, fn_, arr in fields:
                c.append(f'    {t} {fn_}{f"[{arr}]" if arr else ""};')
            c.append(f'}} {n};')
            r.append('#[repr(C)]')
            r.append('#[derive(Clone, Copy)]')
            r.append(f'pub struct {n} {{')
            for t, fn_, arr in fields:
                rt = rtype(t)
                n_ = arr if arr is None or arr.isdigit() else f'{arr} as usize'
                r.append(f'    pub {rident(fn_)}: {f"[{rt}; {n_}]" if arr else rt},')
            r.append('}')
            r.append(f'impl Default for {n} {{')
            r.append('    fn default() -> Self {')
            r.append('        unsafe { core::mem::zeroed() }')
            r.append('    }')
            r.append('}')
            if not noptr:
                c.append(f'typedef {n} *P{n};')
                r.append(f'pub type P{n} = *mut {n};')
            c.append('')
            r.append('')
        elif kw == 'fnptr':
            m = re.match(r'(\w+)\s+(\w+)\s*\((.*)\)', rest)
            n, ret, ps = m.groups()
            params = [p.strip() for p in ps.split(',') if p.strip()]
            c.append(f'typedef {ret} (*{n})({", ".join(params) or "void"});')
            rret = '' if ret == 'VOID' else f' -> {rtype(ret)}'
            r.append(f'pub type {n} = Option<unsafe extern "C" fn({", ".join(rtype(p) for p in params)}){rret}>;')
        elif kw == 'fn':
            m = re.match(r'([\w.]+)\s+(\w+)\s+(\w+)\s*\((.*)\)', rest)
            if not m:
                errors.append(f'{name}: cannot read: {s}')
                continue
            mod, ret, fname, ps = m.groups()
            params = parse_params(ps)
            if '.' in mod:
                mname, what = mod.split('.')
                link = f'{mname}.{what}'
                if mname == 'DOSCALLS' and int(what) not in dos_ok:
                    errors.append(f'{name}: {fname}: DOSCALLS {what} is not in api64.rs')
            else:
                mname, link = mod, f'{mod}.{fname}'
                if mname == 'PMWIN':
                    if fname not in pm_args:
                        errors.append(f'{name}: {fname} is not a 32-bit PMWIN export')
                    elif pm_args[fname] != len(params):
                        errors.append(f'{name}: {fname} has {len(params)} arguments, the 32-bit PMWIN {pm_args[fname]}')
            cps = ', '.join(f'{t} {n}' for t, n in params) or 'VOID'
            c.append(f'{ret} APIENTRY {fname}({cps}) __asm__("{link}");')
            rps = ', '.join(f'{rident(n)}: {rtype(t)}' for t, n in params)
            rret = '' if ret == 'VOID' else f' -> {rtype(ret)}'
            fns.append(f'    #[link_name = "{link}"]\n    pub fn {fname}({rps}){rret};')
        else:
            errors.append(f'{name}: unknown line: {s}')
    if fns:
        r.append('unsafe extern "C" {')
        r.extend(fns)
        r.append('}')
    c += ['', f'#endif /* {guard} */', '']
    os.makedirs(inc_dir, exist_ok=True)
    os.makedirs(rs_dir, exist_ok=True)
    open(os.path.join(inc_dir, f'{name}.h'), 'w').write('\n'.join(c))
    # os2.h only gathers the others (Rust: the os2 crate has them all).
    if name != 'os2':
        open(os.path.join(rs_dir, f'{name}.rs'), 'w').write('\n'.join(r) + '\n')
    return name, len(fns)


# os2def first: the basic types the others use.
files = sorted(f for f in os.listdir(api_dir) if f.endswith('.api'))
files.sort(key=lambda f: (f != 'os2def.api', f))
done = [gen(os.path.join(api_dir, f)) for f in files]
mod = ['//! rs2\'s 64-bit OS/2 API, generated from userland64/api (docs/API64.md).', '//! Generated by tools/scripts/gen_api64.py. Do not edit.', '',
       'pub use core::ffi::c_void;', '']
rust_mods = [n for n, _ in done if n != 'os2']
for n in rust_mods:
    mod.append(f'pub mod {n};')
for n in rust_mods:
    mod.append(f'pub use {n}::*;')
open(os.path.join(rs_dir, 'mod.rs'), 'w').write('\n'.join(mod) + '\n')
for e in errors:
    print('gen_api64:', e, file=sys.stderr)
print(', '.join(f'{n}: {k} functions' for n, k in done))
sys.exit(1 if errors else 0)
