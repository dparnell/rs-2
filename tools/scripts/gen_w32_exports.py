#!/usr/bin/env python3
"""Make a Win32 DLL's exports.def (docs/WIN32.md): every
`pub ... extern "stdcall" fn NAME` in its src/*.rs is exported under its
name; exports.extra lines (forwarders, ordinals) come first.

    python3 -I tools/scripts/gen_w32_exports.py userland/w32kern
"""
import os
import re
import sys

crate = sys.argv[1]
names = set()
for root, _, files in os.walk(os.path.join(crate, "src")):
    for f in files:
        if f.endswith(".rs"):
            text = open(os.path.join(root, f)).read()
            names.update(re.findall(r'pub (?:unsafe )?extern "stdcall" fn (\w+)', text))
extra_path = os.path.join(crate, "exports.extra")
extra = [l.rstrip("\n") for l in open(extra_path)] if os.path.exists(extra_path) else []
taken = set()
for l in extra:
    m = re.match(r"\s*(\w+)", l)
    if m and not l.lstrip().startswith(";"):
        taken.add(m.group(1))
out = ["; Generated by tools/scripts/gen_w32_exports.py from src/*.rs and exports.extra"]
out += extra
ordinal = 100
for n in sorted(names - taken):
    out.append(f"{n} @{ordinal}")
    ordinal += 1
open(os.path.join(crate, "exports.def"), "w").write("\n".join(out) + "\n")
print(f"{len(names - taken)} exports, {len(extra)} extra lines")
