#!/usr/bin/env python3
"""Make a Win32 DLL's exports.def and src/thunks.rs (docs/WIN32.md).

Every `pub ... extern "stdcall" fn NAME(...)` in the crate's src/*.rs is
exported under its name, through a thunk: Windows programs call with a
stack only 4-byte aligned, and Rust code for i686 assumes 16 (its SSE
spills fault otherwise). The thunk realigns the stack, copies the
arguments (their size from the Rust signature: 8 bytes for i64, u64 and
f64, else 4), calls the function and returns as stdcall.

exports.extra lines come first (forwarders, fixed ordinals); a line there
naming a stdcall function gets its thunk too.

    python3 -I tools/scripts/gen_w32_exports.py userland/w32kern
"""
import os
import re
import sys

crate = sys.argv[1]
sigs = {}
pat = re.compile(r'pub (?:unsafe )?extern "stdcall" fn (\w+)\s*\((.*?)\)\s*(?:->|\{|where)', re.S)
for root, _, files in os.walk(os.path.join(crate, "src")):
    for f in sorted(files):
        if f.endswith(".rs") and f != "thunks.rs":
            text = open(os.path.join(root, f)).read()
            for name, params in pat.findall(text):
                size = 0
                depth = 0
                cur = ""
                parts = []
                for ch in params:
                    if ch in "<([":
                        depth += 1
                    elif ch in ">)]":
                        depth -= 1
                    if ch == "," and depth == 0:
                        parts.append(cur)
                        cur = ""
                    else:
                        cur += ch
                if cur.strip():
                    parts.append(cur)
                for p in parts:
                    ty = p.split(":", 1)[1].strip() if ":" in p else ""
                    size += 8 if ty in ("i64", "u64", "f64") else 4
                sigs[name] = size

extra_path = os.path.join(crate, "exports.extra")
extra = [l.rstrip("\n") for l in open(extra_path)] if os.path.exists(extra_path) else []
out = ["; Generated by tools/scripts/gen_w32_exports.py from src/*.rs and exports.extra"]
taken = set()
for l in extra:
    m = re.match(r"\s*(\w+)\s*(@\d+)?\s*$", l)
    if m and not l.lstrip().startswith(";") and m.group(1) in sigs:
        out.append(f"{m.group(1)}=__w32t_{m.group(1)} {m.group(2) or ''}".rstrip())
        taken.add(m.group(1))
        continue
    m = re.match(r"\s*(\w+)", l)
    if m and not l.lstrip().startswith(";"):
        taken.add(m.group(1))
    out.append(l)
ordinal = 100
for n in sorted(set(sigs) - taken):
    out.append(f"{n}=__w32t_{n} @{ordinal}")
    ordinal += 1
open(os.path.join(crate, "exports.def"), "w").write("\n".join(out) + "\n")

asm = [
    "//! Generated by tools/scripts/gen_w32_exports.py: the exports' entry",
    "//! thunks, which realign the stack to 16 bytes for Rust (Windows",
    "//! programs keep it 4-byte aligned), copy the arguments and call.",
    "",
    "core::arch::global_asm!(",
]
for n in sorted(sigs):
    size = sigs[n]
    pad = (size + 15) // 16 * 16
    asm += [
        f'    ".globl __w32t_{n}",',
        f'    "__w32t_{n}:",',
        '    "push ebp",',
        '    "mov ebp, esp",',
        '    "and esp, -16",',
    ]
    if pad:
        asm.append(f'    "sub esp, {pad}",')
    for i in range(size // 4):
        asm += [f'    "mov eax, [ebp+{8 + i * 4}]",', f'    "mov [esp+{i * 4}], eax",']
    asm += [
        f'    "call {n}",',
        '    "mov esp, ebp",',
        '    "pop ebp",',
        f'    "ret {size}",' if size else '    "ret",',
    ]
asm += [");", ""]
open(os.path.join(crate, "src", "thunks.rs"), "w").write("\n".join(asm))
print(f"{len(sigs)} stdcall functions, {len(set(sigs) - taken)} exported by name, {len(extra)} extra lines")
