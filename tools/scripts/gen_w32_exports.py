#!/usr/bin/env python3
"""Make a Win32 DLL's exports.def and src/thunks.rs (docs/WIN32.md).

Every `pub ... extern "stdcall" fn NAME(...)` and `pub ... extern "C" fn
NAME(...)` in the crate's src/*.rs is exported under its name (not
`_start` and not names starting with `rs2_`), through a thunk: Windows
programs call with a stack only 4-byte aligned, and Rust code for i686
assumes 16 (its SSE spills fault otherwise). The thunk realigns the
stack, copies the arguments (their size from the Rust signature: 8 bytes
for i64, u64 and f64, else 4), calls the function and returns as stdcall
(popping them) or cdecl.

exports.extra lines come first:
    NAME [@n]                 an export (a function found here gets its
                              thunk; anything else, data, is as it is)
    NAME=MODULE.n [@n]        a forwarder
    NAME=va TARGET K [@n]     a C function with variable arguments: its K
                              fixed arguments and a va_list (the address
                              of the rest) go to TARGET, a function here
    NAME cdecl|stdcall N      a function made by a macro (not found in
                              the source), N bytes of arguments: its thunk

    python3 -I tools/scripts/gen_w32_exports.py userland/w32kern
"""
import os
import re
import sys

crate = sys.argv[1]
sigs = {}
conv = {}
pat = re.compile(r'pub (?:unsafe )?extern "(stdcall|C)" fn (\w+)\s*\((.*?)\)\s*(?:->|\{|where)', re.S)
for root, _, files in os.walk(os.path.join(crate, "src")):
    for f in sorted(files):
        if f.endswith(".rs") and f != "thunks.rs":
            text = open(os.path.join(root, f)).read()
            for cc, name, params in pat.findall(text):
                if name == "_start" or name.startswith("rs2_"):
                    continue
                size = 0
                depth = 0
                cur = ""
                parts = []
                for ch in params:
                    if ch in "<([":
                        depth += 1
                    elif ch in ">)]":
                        depth -= 1
                    if ch == "," and depth == 0:
                        parts.append(cur)
                        cur = ""
                    else:
                        cur += ch
                if cur.strip():
                    parts.append(cur)
                for p in parts:
                    ty = p.split(":", 1)[1].strip() if ":" in p else ""
                    size += 8 if ty in ("i64", "u64", "f64") else 4
                sigs[name] = size
                conv[name] = cc

extra_path = os.path.join(crate, "exports.extra")
extra = [l.rstrip("\n") for l in open(extra_path)] if os.path.exists(extra_path) else []
declared = []
for l in extra:
    m = re.match(r"\s*(\w+)\s+(cdecl|stdcall)\s+(\d+)\s*$", l)
    if m:
        sigs[m.group(1)] = int(m.group(3))
        conv[m.group(1)] = "C" if m.group(2) == "cdecl" else "stdcall"
        declared.append(m.group(1))
extra = [l for l in extra if not re.match(r"\s*\w+\s+(cdecl|stdcall)\s+\d+\s*$", l)]
out = ["; Generated by tools/scripts/gen_w32_exports.py from src/*.rs and exports.extra"]
taken = set()
varargs = []
for l in extra:
    s = l.strip()
    if not s or s.startswith(";"):
        out.append(l)
        continue
    m = re.match(r"(\w+)\s*=\s*va\s+(\w+)\s+(\d+)\s*(@\d+)?$", s)
    if m:
        name, target, k, ordn = m.group(1), m.group(2), int(m.group(3)), m.group(4) or ""
        if target not in sigs:
            sys.exit(f"{name}: no function {target}")
        varargs.append((name, target, k))
        out.append(f"{name}=__w32v_{name} {ordn}".rstrip())
        taken.add(name)
        continue
    m = re.match(r"(\w+)\s*(@\d+)?$", s)
    if m and m.group(1) in sigs:
        out.append(f"{m.group(1)}=__w32t_{m.group(1)} {m.group(2) or ''}".rstrip())
        taken.add(m.group(1))
        continue
    m = re.match(r"(\w+)", s)
    if m:
        taken.add(m.group(1))
    out.append(l)
ordinal = 100
for l in out:
    for o in re.findall(r"@(\d+)", l):
        ordinal = max(ordinal, int(o) + 1)
for n in sorted(set(sigs) - taken):
    out.append(f"{n}=__w32t_{n} @{ordinal}")
    ordinal += 1
open(os.path.join(crate, "exports.def"), "w").write("\n".join(out) + "\n")

asm = [
    "//! Generated by tools/scripts/gen_w32_exports.py: the exports' entry",
    "//! thunks, which realign the stack to 16 bytes for Rust (Windows",
    "//! programs keep it 4-byte aligned), copy the arguments and call.",
    "",
    "core::arch::global_asm!(",
]
for n in sorted(sigs):
    size = sigs[n]
    pad = (size + 15) // 16 * 16
    asm += [
        f'    ".globl __w32t_{n}",',
        f'    "__w32t_{n}:",',
        '    "push ebp",',
        '    "mov ebp, esp",',
        '    "and esp, -16",',
    ]
    if pad:
        asm.append(f'    "sub esp, {pad}",')
    for i in range(size // 4):
        asm += [f'    "mov eax, [ebp+{8 + i * 4}]",', f'    "mov [esp+{i * 4}], eax",']
    asm += [
        f'    "call {n}",',
        '    "mov esp, ebp",',
        '    "pop ebp",',
        f'    "ret {size}",' if size and conv[n] == "stdcall" else '    "ret",',
    ]
for name, target, k in varargs:
    # The fixed arguments again, then the address of the variable ones:
    # each push reaches back the same distance.
    asm += [
        f'    ".globl __w32v_{name}",',
        f'    "__w32v_{name}:",',
        f'    "lea eax, [esp+{4 + 4 * k}]",',
        '    "push eax",',
    ]
    asm += [f'    "push dword ptr [esp+{4 * (k + 1)}]",'] * k
    asm += [
        f'    "call __w32t_{target}",',
        f'    "add esp, {4 * (k + 1)}",' if conv[target] == "C" else '    "nop",',
        '    "ret",',
    ]
asm += [");", ""]
open(os.path.join(crate, "src", "thunks.rs"), "w").write("\n".join(asm))
print(f"{len(sigs)} functions, {len(set(sigs) - taken)} exported by name, {len(varargs)} with variable arguments, {len(extra)} extra lines")
