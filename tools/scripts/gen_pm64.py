"""Generate the 64-bit PMWIN's thunks (docs/API64.md).

Reads the 32-bit PMWIN's export trampolines (userland/pmwin/src/exports.rs:
`__a_NAME => path, ARGS, index;`) and writes userland64/pmwin/src/thunks.rs:
one `thunk!` line per export (name, which arguments are pointers and
which are MPARAMs, the arguments), except the calls
userland64/pmwin/src/lib.rs converts itself (SPECIAL there, read from its
`// special:` lines).

Pointer arguments are found in the 32-bit functions' Rust signatures
(userland/pmwin/src, userland/pmgpi/src): raw pointer types, and the
`u32` parameters named in POINTER_NAMES (PVOID and PFN passed as ULONG);
`mp1`/`mp2` are MPARAMs. The thunks refuse pointers above 4 GB and
MPARAMs that are not 32-bit values instead of truncating them
(docs/API64.md).

usage: python3 -I tools/scripts/gen_pm64.py
"""
import os, re

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = open(os.path.join(root, 'userland/pmwin/src/exports.rs')).read()
lib = open(os.path.join(root, 'userland64/pmwin/src/lib.rs')).read()
special = set()
for line in lib.splitlines():
    m = re.match(r'\s*// special: (.*)', line)
    if m:
        special.update(m.group(1).split())

# u32 parameters that hold pointers (PVOID, PFN, PSZ as ULONG).
POINTER_NAMES = {'pv', 'pres', 'ctl', 'params', 'types', '_p', 'pfn', 'proc_'}
POINTER_ARGS = {('WinQueryPresParam', 'pid')}

sources = {}
for d in ('userland/pmwin/src', 'userland/pmgpi/src'):
    for dirpath, _, files in os.walk(os.path.join(root, d)):
        for f in files:
            if f.endswith('.rs'):
                sources[os.path.join(dirpath, f)] = open(os.path.join(dirpath, f)).read()

def masks(name, fn, n):
    """(pointer mask, MPARAM mask) of the 32-bit function `fn`."""
    for text in sources.values():
        m = re.search(r'extern "(?:C|system)" fn ' + fn + r'\s*\(([^)]*)\)', text)
        if m:
            break
    else:
        raise SystemExit(f'gen_pm64: no signature for {name} ({fn})')
    params = [p.strip() for p in m.group(1).split(',') if p.strip()]
    if len(params) != n:
        raise SystemExit(f'gen_pm64: {name}: {len(params)} parameters, {n} in exports.rs')
    ptr = mp = 0
    for i, p in enumerate(params):
        pname, ty = (x.strip() for x in p.split(':', 1))
        if '*' in ty or (ty == 'u32' and (pname in POINTER_NAMES or (name, pname) in POINTER_ARGS)):
            ptr |= 1 << i
        elif pname.lstrip('_') in ('mp1', 'mp2'):
            mp |= 1 << i
    return ptr, mp

entries = re.findall(r'__a_(\w+) => ([\w:]+), (\d+), \d+;', src)
out = ['// Generated by tools/scripts/gen_pm64.py from the 32-bit PMWIN\'s',
       '// exports (name, pointer and MPARAM argument masks, arguments).',
       '// Do not edit.',
       '',
       'thunks! {']
n = 0
for name, path, args in entries:
    if name in special:
        continue
    ptr, mp = masks(name, path.split('::')[-1], int(args))
    params = ' '.join(f'a{i}' for i in range(int(args)))
    out.append(f'    {name} [{ptr:#x}, {mp:#x}] ({params});')
    n += 1
out.append('}')
out.append('')
open(os.path.join(root, 'userland64/pmwin/src/thunks.rs'), 'w').write('\n'.join(out) + '\n')
print(f'{n} thunks, {len(special)} special')
