#!/usr/bin/env python3
"""Write work/disk.txt for `cargo xtask disk --hpfs` from RPMs unpacked in
work/pk/root (docs/PACKAGES.md). Symbolic links become copies of their
targets, empty directories get a placeholder (the manifest lists files
only), and the RPMs of work/pk/rpms go to \\rpms for `rpm --justdb`.
Run from the repository root.
"""
import os, sys
root = 'work/pk/root/@unixroot'
out = []
SKIP = ('usr/share/doc/', 'usr/share/man/', 'usr/share/info/', 'usr/share/locale/', 'usr/include/',)
def add(src, dst):
    out.append(f"{src} -> {dst.replace('/', chr(92))}")
for d, dirs, files in os.walk(root):
    rel = os.path.relpath(d, root)
    rel = '' if rel == '.' else rel + '/'
    if rel.startswith(SKIP):
        continue
    if not dirs and not files:
        add('work/cfg/readme.txt', rel + 'README.TXT')
    for f in files + [x for x in dirs if os.path.islink(os.path.join(d, x))]:
        p = os.path.join(d, f)
        if os.path.islink(p):
            t = os.readlink(p)
            if t.startswith('/@unixroot/'):
                q = os.path.join(root, t[len('/@unixroot/'):])
            else:
                q = os.path.join(d, t)
            if not os.path.isfile(q):
                print('skip link', p, '->', t, file=sys.stderr)
                continue
            add(os.path.normpath(q), rel + f)
        else:
            add(p, rel + f)
for extra in ('HOME', 'TMP', 'var/log', 'var/run'):
    add('work/cfg/readme.txt', extra + '/README.TXT')
for f in sorted(os.listdir('work/pk/rpms')):
    if f.endswith('.rpm'):
        add('work/pk/rpms/' + f, 'rpms/' + f)
extra = 'work/pk/disk-extra.txt'
if os.path.exists(extra):
    out += [l.rstrip() for l in open(extra) if l.strip()]
open('work/disk.txt', 'w').write('# generated by mkdisk.py: package manager test disk\n' + '\n'.join(out) + '\n')
print(len(out), 'files')
