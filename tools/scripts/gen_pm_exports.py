"""Generate a DLL's export trampolines and exports.def.

Every `#[unsafe(no_mangle)] pub extern "C" fn` in the DLL's sources is
exported under its own name through a trampoline that aligns the stack to
16 bytes (OS/2 compilers only keep 4-byte alignment, Rust code assumes 16)
and copies the arguments (`_System`: the caller removes them). Ordinals
come from a Toolkit import library dumped with omfimp.py (os2386.lib for
the PM DLLs, tcpip32.lib, so32dll.lib, ...; MODULE as the library names
it). Gpi* and Dev* functions of PMWIN get 4000 + the PMGPI ordinal, and
PMWIN's run also regenerates PMGPI.DLL's forwarders (the forward! list in
../pmgpi/src/lib.rs and ../pmgpi/exports.def, plus ../pmgpi/exports.extra:
its 16-bit entries, LX forwarders to PMWIN); PMWIN's and PMSHAPI's
regenerate PMMERGE.DLL's (gen_pmmerge_forwards.py). A DLL that has src/lock.rs
takes its lock in every trampoline (crate::lock::enter/leave). Lines of
DLLDIR/exports.extra (data exports, `NAME=symbol @ordinal`) are appended
to exports.def as they are. rs2-private functions that the Toolkit does
not know get their ordinals from DLLDIR/exports.private (`NAME ordinal`
lines).

usage: python3 -I gen_pm_exports.py LIB.TSV DLLDIR MODULE
"""
import glob, os, re, sys

tsv_path, dll_dir, module = sys.argv[1:4]
ords = {}
for line in open(tsv_path):
    m, o, n = line.rstrip('\n').split('\t')[:3]
    if o.isdigit():
        ords.setdefault((m, n), int(o))

private = {}
priv_path = f'{dll_dir}/exports.private'
if os.path.exists(priv_path):
    for line in open(priv_path):
        if line.strip() and not line.startswith(';'):
            n, o = line.split()
            private[n] = int(o)

funcs = []
for f in sorted(glob.glob(f'{dll_dir}/src/*.rs')):
    mod = f.rsplit('/', 1)[1][:-3]
    if mod == 'exports':
        continue
    path = 'crate' if mod == 'lib' else f'crate::{mod}'
    src = open(f).read()
    for m in re.finditer(r'#\[unsafe\(no_mangle\)\]\s*pub extern "C" fn (\w+)\s*\(([^)]*)\)', src):
        name, params = m.group(1), m.group(2).strip()
        if name == '_start':
            continue
        n = 0 if not params else len([p for p in params.split(',') if p.strip()])
        funcs.append((name, n, path))

# A DLL with src/lock.rs serialises its threads: the trampolines call
# crate::lock::enter before the function and crate::lock::leave after it.
locked = os.path.exists(f'{dll_dir}/src/lock.rs')
if locked:
    # A lock that logs what exports return (PMTRACE) has leave_export(eax).
    leave_fn = 'leave_export' if 'fn leave_export' in open(f'{dll_dir}/src/lock.rs').read() else 'leave'
    # ecx = the export's index (crate::exports::NAMES) for PMTRACE.
    body = ['                "push ebp", "mov ebp, esp", "and esp, -16",',
            '                "mov ecx, {idx}", "call {enter}",',
            '                "sub esp, {pad}",',
            '                "push esi", "push edi", "push ecx",',
            '                "lea esi, [ebp + 8]", "lea edi, [esp + 12]", "mov ecx, {n}", "rep movsd",',
            '                "pop ecx", "pop edi", "pop esi",',
            '                "call {f}", "add esp, {pad}",',
            '                "sub esp, 16", "mov [esp], eax", "mov [esp + 4], edx",',
            '                "call {leave}",',
            '                "mov eax, [esp]", "mov edx, [esp + 4]",',
            '                "mov esp, ebp", "pop ebp", "ret",',
            '                pad = const ($copy * 4 + 15) / 16 * 16, n = const $copy, f = sym $target,',
            '                idx = const $idx, enter = sym crate::lock::enter, leave = sym crate::lock::' + leave_fn + ',']
else:
    body = ['                "push ebp", "mov ebp, esp", "and esp, -16",',
            '                "sub esp, {pad}",',
            '                "push esi", "push edi", "push ecx",',
            '                "lea esi, [ebp + 8]", "lea edi, [esp + 12]", "mov ecx, {n}", "rep movsd",',
            '                "pop ecx", "pop edi", "pop esi",',
            '                "call {f}", "mov esp, ebp", "pop ebp", "ret",',
            '                pad = const ($copy * 4 + 15) / 16 * 16, n = const $copy, f = sym $target,']
rs = ['//! Generated by tools/scripts/gen_pm_exports.py: stack-aligning entry',
      '//! points for the exports (see exports.def).', '',
      'macro_rules! aligned {',
      '    ($($tramp:ident => $target:path, $copy:literal' + (', $idx:literal' if locked else '') + ';)*) => {$(',
      '        #[unsafe(naked)]',
      '        #[unsafe(no_mangle)]',
      '        pub extern "C" fn $tramp() {',
      '            core::arch::naked_asm!('] + body + [
      '            );',
      '        }',
      '    )*};',
      '}', '', 'aligned! {']
defs = ['; Generated by tools/scripts/gen_pm_exports.py']
for name, n, path in funcs:
    if (name.startswith('Gpi') or name.startswith('Dev')) and module == 'PMWIN':
        o = ords.get(('PMGPI', name))
        o = None if o is None else o + 4000
    else:
        o = ords.get((module, name))
    if o is None:
        o = private.get(name)
    if o is None:
        sys.exit(f'no ordinal for {name}')
    rs.append(f'    __a_{name} => {path}::{name}, {n}' + (f', {len(defs) - 1}' if locked else '') + ';')
    defs.append(f'{name}=__a_{name} @{o}')
rs.append('}')
if locked:
    # Names and argument counts by export index (for PMTRACE).
    rs += ['', '/// Export names and argument counts by trampoline index.', f'pub static NAMES: [(&str, u8); {len(funcs)}] = [']
    rs += [f'    ("{name}", {n}),' for name, n, _ in funcs]
    rs.append('];')
extra = f'{dll_dir}/exports.extra'
if os.path.exists(extra):
    defs += [l.rstrip('\n') for l in open(extra) if l.strip() and not l.startswith(';')]
open(f'{dll_dir}/src/exports.rs', 'w').write('\n'.join(rs) + '\n')
open(f'{dll_dir}/exports.def', 'w').write('\n'.join(defs) + '\n')
print(f'{len(funcs)} exports')

if module == 'PMWIN':
    import os
    gpi_dir = os.path.join(os.path.dirname(dll_dir.rstrip('/')), 'pmgpi')
    fwd = sorted(((ords[('PMGPI', n)], n) for n, _, _ in funcs if (n.startswith('Gpi') or n.startswith('Dev'))), key=lambda x: x[0])
    lib = os.path.join(gpi_dir, 'src', 'lib.rs')
    src = open(lib).read()
    head, rest = src.split('forward! {\n', 1)
    tail = rest.split('\n}\n', 1)[1]
    body = ''.join(f'    {n} = {o + 4000};\n' for o, n in fwd)
    open(lib, 'w').write(head + 'forward! {\n' + body + '}\n' + tail)
    gpi_extra = os.path.join(gpi_dir, 'exports.extra')
    gpi16 = [l for l in open(gpi_extra) if l.strip() and not l.startswith(';')] if os.path.exists(gpi_extra) else []
    open(os.path.join(gpi_dir, 'exports.def'), 'w').write('; name @ordinal\n' + ''.join(f'{n} @{o}\n' for o, n in fwd) + ''.join(gpi16))
    print(f'{len(fwd)} PMGPI forwarders')

if module in ('PMWIN', 'PMSHAPI'):
    import subprocess
    here = os.path.dirname(os.path.abspath(__file__))
    subprocess.run([sys.executable, '-I', os.path.join(here, 'gen_pmmerge_forwards.py'),
                    os.path.dirname(os.path.abspath(dll_dir.rstrip('/')))], check=True)
