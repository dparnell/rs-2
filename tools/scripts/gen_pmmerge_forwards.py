"""Generate PMMERGE.DLL's forwarders.

On OS/2 Warp 4 PMWIN, PMGPI and PMSHAPI forward most of their entry
points to PMMERGE.DLL, and some programs (KLONDIKE, OS2CHESS) import
PMMERGE's ordinals directly. userland/pmmerge/ibm-forwards.txt maps
`DLL ordinal PMMERGE-ordinal`; for every one of those entries that rs2's
DLL exports (its exports.def), PMMERGE gets an entry at the PMMERGE
ordinal that jumps to rs2's export (PMGPI functions go straight to PMWIN,
which implements them at 4000 + the PMGPI ordinal).

Writes userland/pmmerge/src/forward.rs (the forward! list),
userland/pmmerge/exports.extra and appends those lines to exports.def.
gen_pm_exports.py runs this after PMWIN and PMSHAPI.

usage: python3 -I gen_pmmerge_forwards.py [USERLAND_DIR]
"""
import os, re, sys

ul = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', '..', 'userland')
pmm = os.path.join(ul, 'pmmerge')


def exports(dll):
    out = {}
    for l in open(os.path.join(ul, dll.lower(), 'exports.def')):
        m = re.match(r'(\w+)(?:=\S+)?\s*@(\d+)', l.strip())
        if m:
            out[int(m.group(2))] = m.group(1)
    return out


win, shapi = exports('PMWIN'), exports('PMSHAPI')
fwd = []
for l in open(os.path.join(pmm, 'ibm-forwards.txt')):
    if not l.strip() or l.startswith(';'):
        continue
    dll, o, po = l.split()
    o, po = int(o), int(po)
    if dll == 'PMWIN' and o in win:
        fwd.append((po, win[o], f'PMWIN.{o}'))
    elif dll == 'PMGPI' and o + 4000 in win:
        fwd.append((po, win[o + 4000], f'PMWIN.{o + 4000}'))
    elif dll == 'PMSHAPI' and o in shapi:
        fwd.append((po, shapi[o], f'PMSHAPI.{o}'))
fwd.sort()

rs = ['//! Generated by tools/scripts/gen_pmmerge_forwards.py: PMMERGE ordinals',
      '//! (as IBM\'s PMWIN, PMGPI and PMSHAPI forward to them) that jump to rs2\'s',
      '//! implementation.', '', 'forward! {']
rs += [f'    {n} = "{t}";' for _, n, t in fwd]
rs.append('}')
open(os.path.join(pmm, 'src', 'forward.rs'), 'w').write('\n'.join(rs) + '\n')

extra = ['; Generated by tools/scripts/gen_pmmerge_forwards.py'] + [f'{n} @{po}' for po, n, _ in fwd]
open(os.path.join(pmm, 'exports.extra'), 'w').write('\n'.join(extra) + '\n')
defs = os.path.join(pmm, 'exports.def')
own = []
for l in open(defs):
    if l.startswith('; Generated by tools/scripts/gen_pmmerge_forwards.py'):
        break
    # Forwarders appended from exports.extra by gen_pm_exports.py.
    if not re.match(r'\w+ @\d+$', l.strip()):
        own.append(l)
open(defs, 'w').write(''.join(own) + '\n'.join(extra) + '\n')
print(f'{len(fwd)} PMMERGE forwarders')
