#!/usr/bin/env python3
# Generates tests/asm/alu.S: a battery of ALU instructions over a table of
# operands, writing results and flags to port E9h (QEMU debugcon).
bin_ops = ['add','adc','sub','sbb','and','or','xor','cmp','test']
regs = {1:('al','bl'),2:('ax','bx'),4:('eax','ebx')}
sn = []  # (label, body, mask, opts)  opts: 1 = two flag variants, 2 = edx output
ARITH=0x08D5
for op in bin_ops:
    for sz,(a,b) in regs.items():
        mask = ARITH if op in ('add','adc','sub','sbb','cmp') else ARITH & ~0x10
        sn.append((f'{op}{sz}', f'{op} {a}, {b}', mask, 1 if op in ('adc','sbb') else 0))
for op in ['inc','dec','neg','not']:
    for sz,(a,b) in regs.items():
        sn.append((f'{op}{sz}', f'{op} {a}', ARITH, 1))
for op in ['rol','ror','rcl','rcr','shl','shr','sar']:
    for sz,(a,b) in regs.items():
        rot = op in ('rol','ror','rcl','rcr')
        sn.append((f'{op}{sz}cl', f'{op} {a}, cl', 0x00C5 if not rot else 0x00C5, 1))
        sn.append((f'{op}{sz}one', f'{op} {a}, 1', 0x08C5, 1))
for sz,(a,b) in regs.items():
    sn.append((f'mul{sz}', f'mul {b}', 0x0801, 2))
    sn.append((f'imul{sz}', f'imul {b}', 0x0801, 2))
sn.append(('imul2_16', 'imul ax, bx', 0x0801, 0))
sn.append(('imul2_32', 'imul eax, ebx', 0x0801, 0))
sn.append(('imul3_16', 'imul ax, bx, -7', 0x0801, 0))
sn.append(('imul3_32', 'imul eax, ebx, 1000', 0x0801, 0))
sn.append(('div8', 'div bl', 0, 2))
sn.append(('div16', 'mov dx, ax\n    shr dx, 3\n    div bx', 0, 2))
sn.append(('div32', 'mov edx, eax\n    shr edx, 5\n    div ebx', 0, 2))
sn.append(('idiv8', 'idiv bl', 0, 2))
sn.append(('idiv16', 'cwd\n    idiv bx', 0, 2))
sn.append(('idiv32', 'cdq\n    idiv ebx', 0, 2))
for op in ['bt','bts','btr','btc']:
    for sz in (2,4):
        a,b = regs[sz]
        sn.append((f'{op}{sz}', f'{op} {a}, {b}', 0x0001, 1))
for op in ['bsf','bsr']:
    for sz in (2,4):
        a,b = regs[sz]
        sn.append((f'{op}{sz}', f'{op} {a}, {b}', 0x0040, 0))
for op in ['shld','shrd']:
    for sz in (2,4):
        a,b = regs[sz]
        sn.append((f'{op}{sz}', f'{op} {a}, {b}, cl', 0x00C5, 1))
# conditions after CMP of each size: a mask of the 16 SETcc results
conds = ['o','no','b','ae','e','ne','be','a','s','ns','p','np','l','ge','le','g']
for sz,(a,b) in regs.items():
    body = [f'cmp {a}, {b}', 'pushf', 'xor esi, esi']
    for i,c in enumerate(conds):
        body += ['popf', 'pushf', f'set{c} dl', 'movzx edx, dl', f'shl edx, {i}', 'or esi, edx']
    body += ['popf', 'mov eax, esi']
    sn.append((f'cond{sz}', '\n    '.join(body), 0, 0))
sn.append(('cwd', 'cwd', 0, 2))
sn.append(('cdq', 'cdq', 0, 2))
sn.append(('cbw', 'cbw', 0, 0))
sn.append(('cwde', 'cwde', 0, 0))
sn.append(('xadd16', 'xadd ax, bx\n    add ax, bx', ARITH, 0))
sn.append(('cmpxchg32', 'mov edx, ebx\n    cmpxchg edx, ecx\n    xor eax, edx', ARITH, 0))
sn.append(('bswap', 'bswap eax', 0, 0))
sn.append(('lea16', 'lea ax, [bx+di+0x1234]', 0, 0))

un8 = [('daa','daa',0x00D5),('das','das',0x00D5),('aaa','aaa',0x0011),('aas','aas',0x0011),
       ('aam','aam',0x00C4),('aam16','aam 16',0x00C4),('aad','aad',0x00C4),('aad7','aad 7',0x00C4),('salc','salc',0)]

vals = [0, 1, 2, 7, 8, 9, 0x1f, 0x7f, 0x80, 0xff, 0x7fff, 0x8000, 0xffff, 0x80000000, 0xffffffff, 0x9abcdef1]

out = []
w = out.append
w('''// Generated by tools/scripts/gen_cputest.py (do not edit): ALU
// instructions over a table of operands; each case writes EAX (and EDX),
// then the flags masked to the defined ones, to port E9h. Runs as the
// payload of tests/asm/boot.S at 1000:0000 (QEMU) or directly (emulator).
.intel_syntax noprefix
.code16
// LLVM assembles near CALL and RET in .code16 with an operand size prefix.
.macro call16 dest
    .byte 0xe8
    .word \\dest - . - 2
.endm
.macro ret16
    .byte 0xc3
.endm
.equ NVALS, 16
.text
.globl _start
_start:
    cli
    mov ax, cs
    mov ds, ax
    mov es, ax
    mov ss, ax
    mov sp, 0xfff0
    xor ax, ax
    mov fs, ax
    mov word ptr fs:[0], offset de_handler
    mov fs:[2], cs
    mov si, offset table
next_snip:
    mov ax, [si]
    test ax, ax
    jz binary_done
    mov [cur_fn], ax
    mov ax, [si+2]
    mov [cur_mask], ax
    mov ax, [si+4]
    mov [cur_opt], ax
    push si
    call16 run_snip
    pop si
    add si, 6
    jmp next_snip
binary_done:
    mov si, offset table8
next8:
    mov ax, [si]
    test ax, ax
    jz all_done
    mov [cur_fn], ax
    mov ax, [si+2]
    mov [cur_mask], ax
    push si
    call16 run8
    pop si
    add si, 4
    jmp next8
all_done:
    mov al, 0
    out 0xf4, al
    cli
1:  hlt
    jmp 1b

// One snippet over all operand pairs.
run_snip:
    xor bp, bp
.Li:
    xor di, di
.Lj:
    mov word ptr [cur_fl], 0x0002
.Lv:
    mov eax, ds:[bp + vals]
    mov ebx, ds:[di + vals]
    mov ecx, ebx
    xor edx, edx
    push di
    push bp
    xor di, di
    xor si, si
    push word ptr [cur_fl]
    popf
    call word ptr [cur_fn]
    pushf
    pop word ptr [res_fl]
    pop bp
    pop di
    call16 out32
    test word ptr [cur_opt], 2
    jz 2f
    mov eax, edx
    call16 out32
2:  mov ax, [res_fl]
    and ax, [cur_mask]
    call16 out16
    test word ptr [cur_opt], 1
    jz 3f
    cmp word ptr [cur_fl], 0x0002
    jne 3f
    mov word ptr [cur_fl], 0x08D7
    jmp .Lv
3:  add di, 4
    cmp di, NVALS*4
    jb .Lj
    add bp, 4
    cmp bp, NVALS*4
    jb .Li
    ret16

// An 8-bit unary snippet over AL 0-255 with CF/AF combinations.
run8:
    xor cx, cx
.L8:
    mov bx, offset fl8
.L8f:
    mov al, cl
    mov ah, 255
    sub ah, cl
    push cx
    push bx
    push word ptr [bx]
    popf
    call word ptr [cur_fn]
    pushf
    pop word ptr [res_fl]
    pop bx
    pop cx
    call16 out16
    mov ax, [res_fl]
    and ax, [cur_mask]
    call16 out16
    add bx, 2
    cmp bx, offset fl8 + 8
    jb .L8f
    inc cx
    cmp cx, 256
    jb .L8
    ret16

out32:
    call16 out16
    shr eax, 16
out16:
    push ax
    out 0xe9, al
    mov al, ah
    out 0xe9, al
    pop ax
    ret16

de_handler:
    add sp, 6
    mov eax, 0xdededede
    mov edx, 0xdededede
    push 0x0002
    popf
    ret16
''')
assert len(vals) == 16
w('.balign 4\nvals:')
for v in vals: w(f'    .long 0x{v:x}')
w('fl8: .word 0x0002, 0x0003, 0x0012, 0x0013')
w('cur_fn: .word 0\ncur_mask: .word 0\ncur_opt: .word 0\ncur_fl: .word 0\nres_fl: .word 0')
w('table:')
for (l,b,m,o) in sn: w(f'    .word s_{l}, 0x{m:04x}, {o}')
w('    .word 0')
w('table8:')
for (l,b,m) in un8: w(f'    .word u_{l}, 0x{m:04x}')
w('    .word 0')
for (l,b,m,o) in sn: w(f's_{l}:\n    {b}\n    ret16')
for (l,b,m) in un8: w(f'u_{l}:\n    {b}\n    ret16')
open(__import__('os').path.join(__import__('os').path.dirname(__file__),'../../crates/x86emu/tests/asm/alu.S'),'w').write('\n'.join(out)+'\n')
print(len(sn), 'snippets')
# The layout of the output, for the test's error messages.
with open(__import__('os').path.join(__import__('os').path.dirname(__file__),'../../crates/x86emu/tests/asm/alu.layout'),'w') as f:
    f.write(' '.join('%x' % v for v in vals) + '\n')
    for (l,b,m,o) in sn: f.write(f'{l} {o}\n')
    for (l,b,m) in un8: f.write(f'{l} 8\n')
