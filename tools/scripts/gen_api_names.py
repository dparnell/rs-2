"""Generate kernel/src/api/names.rs from the OS/2 Toolkit import libraries.

usage: python3 -I gen_api_names.py work/media/boot/toolkit/os2tk45/lib > kernel/src/api/names.rs

For every module implemented behind the API gate it records each ordinal's
display name, all import names (for import-by-name) and whether the entry
uses the 16-bit far _Pascal convention.
"""
import os, re, subprocess, sys
here = os.path.dirname(os.path.abspath(__file__))
libdir = sys.argv[1]
libs = [os.path.join(libdir, f) for f in sorted(os.listdir(libdir)) if f.endswith('.lib')]
out = subprocess.run([sys.executable, '-I', os.path.join(here, 'omfimp.py')] + libs,
                     capture_output=True, text=True, check=True).stdout
MODULES = ["DOSCALLS", "VIOCALLS", "KBDCALLS", "MOUCALLS", "MSG", "NLS", "SESMGR", "QUECALLS"]
names = {}  # (mod, ord) -> set(names)
for line in out.splitlines():
    m, o, n = line.split('\t')
    m = m.upper()
    if m not in MODULES or not o:
        continue
    names.setdefault((m, int(o)), set()).add(n)

def is16(m, o, ns):
    up = [n.upper() for n in ns]
    if any(re.match(r'^[A-Z]+16', n) for n in up):
        return True
    if any(re.match(r'^[A-Z]+32', n) for n in up):
        return False
    if m == 'DOSCALLS':
        return o < 200
    return True

def display(ns):
    # Prefer a mixed-case name without a 16/32 infix, e.g. DosGetInfoBlocks.
    def score(n):
        return (n.isupper(), bool(re.match(r'^[A-Za-z]+(16|32)', n)), len(n), n)
    return sorted(ns, key=score)[0]

entries = []   # (mod_idx, ord, is16, display)
aliases = []   # (MODULE, NAME_UPPER, ord)
for (m, o), ns in sorted(names.items(), key=lambda x: (MODULES.index(x[0][0]), x[0][1])):
    entries.append((MODULES.index(m), o, is16(m, o, ns), display(ns)))
    for n in ns:
        aliases.append((m, n.upper(), o))
aliases = sorted(set(aliases))

print("// Generated by tools/scripts/gen_api_names.py from the OS/2 Toolkit")
print("// import libraries. Do not edit.")
print()
print("/// (module index, ordinal, 16-bit convention, display name), sorted.")
print("pub static ENTRIES: &[(u8, u16, bool, &str)] = &[")
for e in entries:
    print(f'    ({e[0]}, {e[1]}, {"true" if e[2] else "false"}, "{e[3]}"),')
print("];")
print()
print("/// (module, upper-case import name, ordinal), sorted.")
print("pub static ALIASES: &[(&str, &str, u16)] = &[")
for a in aliases:
    print(f'    ("{a[0]}", "{a[1]}", {a[2]}),')
print("];")
