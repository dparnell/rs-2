/// The text of message `num` with `%1` replaced by `arg`.
pub fn expand(num: u16, arg: &str) -> String {
    let t = TEXT.iter().find(|(n, _)| *n == num).map_or("Error %1", |(_, t)| t);
    let mut s = String::from(t).replace("%1", arg);
    if !t.contains("%1") && !arg.is_empty() {
        s.push(' ');
        s.push_str(arg);
    }
    s
}
