/// The message number of an error subcode.
pub fn number(code: u32) -> Option<u32> {
    CODES.binary_search_by_key(&code, |&(c, _)| c).ok().map(|i| CODES[i].1)
}

/// A message's text (without its prefix and "%0").
pub fn text(num: u32) -> Option<&'static [u8]> {
    let want = alloc::format!("REX{num:04}");
    for l in SRC.lines() {
        if l.starts_with(&want) && l.as_bytes().get(8) == Some(&b':') {
            let t = l[9..].trim_start();
            let t = t.strip_suffix("%0").unwrap_or(t);
            if t.is_empty() {
                return None;
            }
            return Some(t.as_bytes());
        }
    }
    None
}

/// The secondary message of an error subcode, with `&1`... to fill in.
pub fn secondary(code: u32) -> Option<&'static [u8]> {
    text(number(code)?)
}
