static RANGES: [(u16, u16, &[i8]); 5] = [
    (0x03a0, 0x03ce, &R03A0),
    (0x0430, 0x045f, &R0430),
    (0x0490, 0x04cc, &R0490),
    (0x1e00, 0x1ffc, &R1E00),
    (0xff40, 0xff5a, &RFF40),
];


/// The upper-case form of `c`.
pub fn upper(c: u16) -> u16 {
    if c < 0x200 {
        return c.wrapping_add(LOW[c as usize] as u16);
    }
    for &(lo, hi, d) in RANGES.iter() {
        if c < lo {
            break;
        }
        if c <= hi {
            return c.wrapping_add(d[(c - lo) as usize] as u16);
        }
    }
    c
}
